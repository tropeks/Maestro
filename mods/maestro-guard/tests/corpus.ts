const B = (command: string, want: Want, bash?: 'block' | 'pass', cwd?: string): Case => ({
  tool: 'Bash',
  input: { command },
  want,
  ...(bash ? { bash } : {}),
  ...(cwd ? { cwd } : {}),
})
const F = (tool: string, key: string, path: string, want: Want, cwd?: string): Case => ({
  tool,
  input: { [key]: path },
  want,
  ...(cwd ? { cwd } : {}),
})

